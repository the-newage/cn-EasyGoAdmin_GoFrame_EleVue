// ============================== 业务错误码 ==============================

// 业务错误码定义
//
// 响应层统一映射：401 保持原样（前端跳登录），其余非 0 错误码一律降级为 1
// （前端 ResultEnum.ERROR=1 才会弹出 msg 提示），故本文件的码值仅用于日志与语义区分。
var (
	CodeFailed          = gcode.New(1, "操作失败", nil)           // 通用操作失败
	CodeUnauthorized    = gcode.New(401, "登录已过期，请重新登录", nil)  // 未认证
	CodeForbidden       = gcode.New(403, "没有该操作权限", nil)      // 无权限
	CodeParamError      = gcode.New(400, "参数校验失败", nil)       // 参数校验失败
	CodeRecordNotFound  = gcode.New(1010, "记录不存在", nil)       // 记录不存在
	CodeRecordExists    = gcode.New(1009, "记录已存在", nil)       // 记录已存在
	CodeServerError     = gcode.New(500, "服务器内部错误", nil)      // 服务器内部错误
	CodeTooManyRequests = gcode.New(429, "请求过于频繁，请稍后再试", nil) // 限流

	// 认证与账户
	CodeUserNotFound  = gcode.New(1001, "用户不存在", nil)       // 用户不存在
	CodeUserDisabled  = gcode.New(1002, "账号已被禁用", nil)      // 账号已被禁用
	CodePasswordWrong = gcode.New(1003, "密码错误", nil)        // 密码错误
	CodeCaptchaError  = gcode.New(1004, "验证码错误或已过期", nil)   // 验证码错误或已过期
	CodeTokenInvalid  = gcode.New(1008, "Token无效或已失效", nil) // Token无效或已失效
	CodeOldPwdWrong   = gcode.New(1012, "原密码错误", nil)       // 原密码错误

	// 租户
	CodeTenantExpired   = gcode.New(1005, "租户已过期", nil)     // 租户已过期
	CodeTenantDisabled  = gcode.New(1006, "租户已禁用", nil)     // 租户已禁用
	CodeTenantUserLimit = gcode.New(1007, "租户用户数已达上限", nil) // 租户用户数已达上限
	CodeTenantNotFound  = gcode.New(1013, "租户不存在", nil)     // 租户不存在

	// 业务约束
	CodeHasChildren = gcode.New(1011, "存在下级或关联记录，不能删除", nil) // 存在下级或关联记录
	CodeInUse       = gcode.New(1014, "记录已被引用，不能删除", nil)    // 记录已被引用
	CodeDemoMode    = gcode.New(1015, "演示环境，禁止操作!", nil)     // 演示环境禁止操作
)

